import { chromium } from '@playwright/test';
import { resolveChromium } from './tests/browser-path.ts';
const executablePath = resolveChromium();
const b = await chromium.launch({ ...(executablePath?{executablePath}:{}) });
const D='/tmp/claude-0/-home-user/5d7b8882-f533-5ead-8fb3-8720590302f5/scratchpad/polish';
const page = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs=[]; page.on('pageerror', e=>errs.push(String(e)));
await page.goto('http://127.0.0.1:4173/?hole=c6-2', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.evaluate(() => {
  const s = window.gravityGolf.session; const h = s.world.hole;
  s.shoot({x:1,y:0}, 0.05);
  s.ball.position = { x: h.position.x, y: h.position.y - h.radius * 0.4 };
  s.ball.velocity = {x:0,y:0};
});
await page.waitForTimeout(1500);
await page.screenshot({ path: `${D}/confetti.png` });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${D}/confetti2.png` });
console.log(errs);
await b.close();
